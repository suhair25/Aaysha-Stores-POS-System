import 'package:firebase_core/firebase_core.dart' show Firebase;
import 'package:aaysha_stores/utils/logger.dart';

/// Firebase configuration
/// This file contains Firebase initialization setup
/// 
/// Before running the app, ensure:
/// 1. Firebase project is created at console.firebase.google.com
/// 2. Download google-services.json (Android) and GoogleService-Info.plist (iOS)
/// 3. Place in android/app/src/main/ and ios/Runner/ respectively
/// 4. Run: flutter pub get && flutter pub add firebase_core

class FirebaseConfig {
  /// Initialize Firebase
  /// Call this once in main() before running the app
  static Future<void> initialize() async {
    try {
      await Firebase.initializeApp();
      AppLogger.success('Firebase initialized successfully');
    } catch (e) {
      AppLogger.error('Firebase initialization failed', e);
      rethrow;
    }
  }

  /// Firebase Project Configuration
  /// Update these values based on your Firebase project
  static const String projectId = 'aaysha-stores';
  static const String apiKey = 'YOUR_API_KEY'; // Replace with actual key
  static const String appId = 'YOUR_APP_ID'; // Replace with actual app ID
  static const String messagingSenderId = 'YOUR_MESSAGING_SENDER_ID'; // For FCM

  // Firestore Configuration
  static const bool enableOfflinePersistence = true;
  static const int cacheSizeBytes = 40 * 1024 * 1024; // 40 MB cache

  // Firebase Security Rules Notes
  static const String securityRulesNotes = r'''
  Apply these security rules to Firestore:

  rules_version = '2';
  service cloud.firestore {
    match /databases/{database}/documents {
      
      // Users collection - authenticated users only
      match /users/{uid} {
        allow read: if request.auth.uid == uid;
        allow create: if request.auth.uid == uid;
        allow update: if request.auth.uid == uid;
        allow delete: if request.auth.uid == uid;
      }

      // Products - readable by all authenticated users
      // Writable only by admins
      match /products/{productId} {
        allow read: if request.auth != null;
        allow create, update, delete: if request.auth != null && 
          get(/databases/$(database)/documents/users/$(request.auth.uid)).data.role == 'OWNER';
      }

      // Sales - readable by cashiers (create their own), admins see all
      // Cost price hidden from cashiers
      match /sales/{saleId} {
        allow read: if request.auth != null && 
          (get(/databases/$(database)/documents/users/$(request.auth.uid)).data.role == 'OWNER' ||
           resource.data.cashierId == request.auth.uid);
        allow create: if request.auth != null;
        allow update: if request.auth != null && resource.data.cashierId == request.auth.uid;
      }

      // Admin Records - only owners can read/write
      match /admin_records/{recordId} {
        allow read, write: if request.auth != null && 
          get(/databases/$(database)/documents/users/$(request.auth.uid)).data.role == 'OWNER';
      }

      // Expenses - readable by admins only
      match /expenses/{expenseId} {
        allow read: if request.auth != null && 
          get(/databases/$(database)/documents/users/$(request.auth.uid)).data.role == 'OWNER';
        allow create: if request.auth != null;
        allow update, delete: if request.auth != null && 
          get(/databases/$(database)/documents/users/$(request.auth.uid)).data.role == 'OWNER';
      }

      // Reports - readable by admins only
      match /reports/{reportId} {
        allow read: if request.auth != null && 
          get(/databases/$(database)/documents/users/$(request.auth.uid)).data.role == 'OWNER';
        allow write: if false; // Generated by cloud functions
      }

      // Settings - readable by authenticated users, writable by admins
      match /settings/{document=**} {
        allow read: if request.auth != null;
        allow write: if request.auth != null && 
          get(/databases/$(database)/documents/users/$(request.auth.uid)).data.role == 'OWNER';
      }
    }
  }
  ''';
}

